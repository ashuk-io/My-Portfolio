name = 'Ashutosh'
print(name[0:2]) # goes from 0 to 2-1

print(name[2:-1]) # same as [2:7]

#print(name[0:8:n])     #skip n-1 characters 
print(name[0:8:1]) # (Skips 0 character)
print(name[0:8:2]) # (Skips 1 character)

print(name[:5])    #(same as text[0:5])
print(name[7:])    # replaces the second with length so its [7:8]
print(name[:-3])
print(name[-3:])
print(name[::-1])
print(name[::-2])
print(name[6:1:-1])